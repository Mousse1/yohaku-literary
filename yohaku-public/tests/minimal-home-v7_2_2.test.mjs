import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = p => readFileSync(new URL(p, import.meta.url), 'utf8')
const main = read('../src/main.jsx')
const css = read('../src/style.css')
const html = read('../index.html')
assert.ok(!main.includes('物語の先に'), '古い大型キャッチコピーはない')
assert.ok(!main.includes('hero-art'), '旧ビジュアルの描画を削除')
assert.ok(!main.includes('className="container intro"'), '3つの紹介欄はない')
assert.ok(main.includes('id="works" className="container section home-library"'), '作品検索がメインコンテンツ')
assert.ok(main.includes('value={query} onChange={e=>setQuery(e.target.value)}'), '検索機能を保持')
assert.ok(main.includes('className="classification-filter"'), '分類機能を保持')
assert.ok(css.includes('.home-library{'), 'コンパクトなホーム用スタイルがある')
assert.match(html, /content="v7\.(?:[2-9])(?:\.\d+)?"/, 'HTMLの版表記が更新済み')
console.log('v7.2.2: 大型ヒーローを撤去し、ホームの検索・分類・作品を保持: OK')
